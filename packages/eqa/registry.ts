import {z} from 'zod';
import type {Queryable} from '../db/connection';
import {need,assertSession,type Staff} from '../lab/core';

const pageSchema=z.strictObject({
 q:z.string().trim().max(80).optional(),
 year:z.coerce.number().int().min(2020).max(2100).optional(),
 page:z.coerce.number().int().min(1).max(100000).default(1),
 pageSize:z.coerce.number().int().refine(n=>[25,50,100].includes(n)).default(25)
});
export type EqaRow={
 caseId:string;organizer:string;programYear:number;sampleRef:string;surname:string;firstName:string;pregnancy:'Singleton'|'Twins';
 ln:string;lnHalos:string|null;receivedAt:string|null;
 /** Run of the active slot, from the existing Task List, or null before placement. */
 run:string|null;attemptState:string|null;
 /** Latest report version of the round (the one authoritative report), or null: no report is generated by reading this list. */
 versionId:string|null;versionState:string|null;versionAt:string|null;certifiedAt:string|null;
 versions:number;
};

/** EQA Annual Registry: read-only, built from existing case, round, batch and report records. Access follows result review. */
export async function readEqaRegistry(db:Queryable,user:Staff,raw:unknown={}){
 await assertSession(db,user);need(user,'result.review','read');
 const f=pageSchema.parse(raw);
 const args:unknown[]=[],cond:string[]=[];
 if(f.year){args.push(f.year);cond.push(`e.program_year=$${args.length}`);}
 if(f.q){args.push('%'+f.q.toLowerCase()+'%');cond.push(`(lower(e.sample_ref) LIKE $${args.length} OR lower(e.surname) LIKE $${args.length} OR lower(e.first_name) LIKE $${args.length} OR l.ln LIKE $${args.length} OR lower(COALESCE(n.ln_halos,'')) LIKE $${args.length})`);}
 const where=cond.length?'WHERE '+cond.join(' AND '):'';
 const from=`FROM eqa_case e JOIN case_ln l ON l.case_id=e.case_id JOIN specimen_round r ON r.id=e.round_id LEFT JOIN specimen_lab_number n ON n.round_id=e.round_id`;
 const total=Number((await db.query<{n:string}>(`SELECT count(*)::text n ${from} ${where}`,args)).rows[0].n);
 const pages=Math.max(1,Math.ceil(total/f.pageSize)),page=Math.min(f.page,pages);
 const rows=(await db.query<{
  case_id:string;organizer:string;program_year:number;sample_ref:string;surname:string;first_name:string;pregnancy:'Singleton'|'Twins';
  ln:string;ln_halos:string|null;received_at:Date|null;run:string|null;attempt_state:string|null;
  version_id:string|null;version_state:string|null;version_at:Date|null;certified_at:Date|null;versions:number}>(
  `SELECT e.case_id,e.organizer,e.program_year,e.sample_ref,e.surname,e.first_name,e.pregnancy,l.ln,n.ln_halos,r.received_at,
    (SELECT b.run_label FROM lab_slot_assignment s JOIN lab_batch b ON b.id=s.batch_id JOIN analytical_attempt a ON a.id=s.attempt_id
      WHERE a.round_id=e.round_id AND s.removed_at IS NULL ORDER BY s.assigned_at DESC LIMIT 1) run,
    (SELECT a.state FROM analytical_attempt a WHERE a.round_id=e.round_id ORDER BY a.overall_ordinal DESC LIMIT 1) attempt_state,
    v.id version_id,v.state version_state,v.imported_at version_at,rel.certified_at,
    (SELECT count(*)::int FROM result_report_version x WHERE x.round_id=e.round_id AND x.kind='RESULT') versions
   ${from}
   LEFT JOIN LATERAL (SELECT x.id,x.state,x.imported_at FROM result_report_version x WHERE x.round_id=e.round_id AND x.kind='RESULT' ORDER BY x.imported_at DESC,x.id DESC LIMIT 1) v ON true
   LEFT JOIN LATERAL (SELECT y.certified_at FROM result_release y WHERE y.version_id=v.id AND y.state='Active' LIMIT 1) rel ON true
   ${where} ORDER BY e.program_year DESC,e.created_at DESC,e.case_id LIMIT ${f.pageSize} OFFSET ${(page-1)*f.pageSize}`,args)).rows;
 const iso=(d:Date|null)=>d?new Date(d).toISOString():null;
 const out:EqaRow[]=rows.map(r=>({caseId:r.case_id,organizer:r.organizer,programYear:r.program_year,sampleRef:r.sample_ref,surname:r.surname,firstName:r.first_name,pregnancy:r.pregnancy,
  ln:r.ln,lnHalos:r.ln_halos,receivedAt:iso(r.received_at),run:r.run,attemptState:r.attempt_state,versionId:r.version_id,versionState:r.version_state,versionAt:iso(r.version_at),certifiedAt:iso(r.certified_at),versions:r.versions}));
 const years=(await db.query<{y:number}>('SELECT DISTINCT program_year y FROM eqa_case ORDER BY y DESC')).rows.map(r=>r.y);
 return {rows:out,total,page,pages,pageSize:f.pageSize,years,year:f.year??null,q:f.q??null};
}

/** One slot's recorded measurement. Keys and unit come from the approved task master: slot.N.libraryQc is "library concentration ng/uL". */
export type IqcRow={runLabel:string;runDate:string;control:'PC'|'NC';slot:number;sampleId:string|null;libraryQc:number|null;extractionQc:number|null;
 workbookRevision:number;masterSha256:string;reviewed:boolean;reviewedAt:string|null};
const iqcSchema=z.strictObject({page:z.coerce.number().int().min(1).max(100000).default(1),pageSize:z.coerce.number().int().refine(n=>[25,50,100].includes(n)).default(25),
 control:z.enum(['PC','NC']).optional()});

/**
 * IQC Positive/Negative Control: only recorded values of the control slots (1 = PC, 25 = NC) from each Run's latest approved workbook revision.
 * No thresholds, means, SD or pass/fail are computed here; Blank (slot 40) is never included. A missing value shows as unavailable.
 */
export async function readIqc(db:Queryable,user:Staff,raw:unknown={}){
 await assertSession(db,user);need(user,'result.review','read');
 const f=iqcSchema.parse(raw);
 const control=f.control==='PC'?[1]:f.control==='NC'?[25]:[1,25];
 const base=`FROM lab_batch b JOIN LATERAL (SELECT * FROM task_workbook_revision w WHERE w.batch_id=b.id ORDER BY w.revision DESC LIMIT 1) w ON true
  JOIN lab_batch_slot s ON s.batch_id=b.id AND s.slot_number=ANY($1::int[]) AND s.control_type IN ('positive','negative')
  WHERE b.state<>'Cancelled'`;
 const total=Number((await db.query<{n:string}>(`SELECT count(*)::text n ${base}`,[control])).rows[0].n);
 const pages=Math.max(1,Math.ceil(total/f.pageSize)),page=Math.min(f.page,pages);
 const rows=(await db.query<{run_label:string;created_at:Date;slot_number:number;control_type:string;sample_id:string|null;lib:string|null;ext:string|null;revision:number;master:string;reviewed:boolean;reviewed_at:Date|null}>(
  `SELECT b.run_label,b.created_at,s.slot_number,s.control_type,w.values->>('slot.'||s.slot_number||'.printedSampleId') sample_id,
    w.values->>('slot.'||s.slot_number||'.libraryQc') lib,w.values->>('slot.'||s.slot_number||'.extractionQc') ext,w.revision,w.master_sha256 master,
    EXISTS(SELECT 1 FROM lab_bench_review r WHERE r.workbook_revision_id=w.id AND lab_bench_review_current(r.id)) reviewed,
    (SELECT max(r.created_at) FROM lab_bench_review r WHERE r.workbook_revision_id=w.id AND lab_bench_review_current(r.id)) reviewed_at
   ${base} ORDER BY b.run_year DESC,b.run_number DESC,s.slot_number LIMIT ${f.pageSize} OFFSET ${(page-1)*f.pageSize}`,[control])).rows;
 const num=(v:string|null)=>v===null||v===''||Number.isNaN(Number(v))?null:Number(v);
 const out:IqcRow[]=rows.map(r=>({runLabel:r.run_label,runDate:new Date(r.created_at).toISOString(),control:r.control_type==='positive'?'PC':'NC',slot:r.slot_number,sampleId:r.sample_id,
  libraryQc:num(r.lib),extractionQc:num(r.ext),workbookRevision:r.revision,masterSha256:r.master,reviewed:r.reviewed,reviewedAt:r.reviewed_at?new Date(r.reviewed_at).toISOString():null}));
 return {rows:out,total,page,pages,pageSize:f.pageSize,control:f.control??null};
}
